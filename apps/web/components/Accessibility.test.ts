/**
 * Accessibility of the core views (design non-functional "accessibility";
 * CRT-UX-14-A): automated checks and a keyboard-only walkthrough of Today, Ask,
 * Commitments, Weekly Review, Memory Inspector and Memory Inbox.
 *
 * Each screen is rendered by React into a real DOM (jsdom), exactly as its page
 * renders it, and then:
 *
 *  - axe-core, the engine behind the common browser accessibility checkers, runs
 *    every WCAG 2 A/AA and best-practice rule it has over the document; a
 *    critical violation fails the suite (and so does a serious one). Colour
 *    contrast is the one rule it cannot run without a layout engine; the
 *    grayscale-safe label system has its own test (`Labels.test.ts`).
 *  - a keyboard-only user (`testing/keyboard.ts`: Tab, Shift+Tab, typing, Enter,
 *    Space and Arrow Down, each with the browser's native default action, and no
 *    pointer at all) completes every core task of the screen.
 *
 * The walkthrough transcript and the axe summary are written to
 * `test-results/accessibility/`, the CI artifact the design requires beside the
 * automated checks.
 */

(globalThis as {IS_REACT_ACT_ENVIRONMENT?:boolean}).IS_REACT_ACT_ENVIRONMENT=true;
// Each scenario scans several complete DOM states and walks every keyboard task.
// Under the CI unit stage's four workers, the default 5s expires mid-walk and
// cleanup clears the DOM while that scenario is still running, corrupting the
// next screen's axe result. Keep a bounded integration budget without dropping
// any audit, keyboard action, or assertion.
const CORE_VIEW_TIMEOUT_MS=20_000;
const ARTIFACT_DIRECTORY=resolve('test-results/accessibility');
const report:{screens:Record<string,{states:Record<string,{violations:Array<{id:string;impact:string|null;nodes:number}>;passes:number}>;
  tasks:Array<{task:string;completed:boolean;steps:Step[];navigations:string[]}>}>}={screens:{}};

let root:Root|null=null;
const originalFetch=globalThis.fetch;
afterEach(()=>{act(()=>root?.unmount());root=null;document.body.innerHTML='';globalThis.fetch=originalFetch;});
afterAll(()=>{
  mkdirSync(ARTIFACT_DIRECTORY,{recursive:true});
  writeFileSync(resolve(ARTIFACT_DIRECTORY,'report.json'),JSON.stringify({
    criterion:'CRT-UX-14-A',axeVersion:axe.version,generatedAt:new Date().toISOString(),...report},null,2));
  const lines=['# Keyboard-only walkthrough of the core views','',
    'Generated by `apps/web/components/Accessibility.test.ts` (CRT-UX-14-A). No pointer is used: every step is a key.',''];
  for(const [screen,entry] of Object.entries(report.screens)){
    lines.push('## '+screen,'');
    for(const [state,result] of Object.entries(entry.states)){
      lines.push('- axe, '+state+': '+result.violations.length+' violations ('+result.passes+' rules passed)');
    }
    for(const task of entry.tasks){
      lines.push('','### '+task.task+(task.completed?'':' (NOT COMPLETED)'),'');
      task.steps.forEach((step,index)=>lines.push((index+1)+'. `'+step.key+'` on '+step.target+' → '+step.outcome));
    }
    lines.push('');
  }
  writeFileSync(resolve(ARTIFACT_DIRECTORY,'keyboard-walkthrough.md'),lines.join('\n'));
});

async function mount(element:ReactElement){
  if(root){const previous=root;act(()=>previous.unmount());root=null;}
  document.body.innerHTML='';
  // The served document declares its language (pages/_document.tsx); so does this one.
  document.documentElement.lang=/<Html lang="([a-z-]+)">/.exec(readFileSync(resolve('apps/web/pages/_document.tsx'),'utf8'))?.[1]??'';
  document.title='Uai';
  const container=document.createElement('div');
  container.id='__next';
  document.body.appendChild(container);
  root=createRoot(container);
  await act(async()=>{root!.render(element);});
}

function entry(screen:string){return report.screens[screen]??=(report.screens[screen]={states:{},tasks:[]});}

/** axe over the whole document: no critical and no serious violation. */
async function audit(screen:string,state:string){
  const results=await axe.run(document,{rules:{'color-contrast':{enabled:false}}});
  entry(screen).states[state]={violations:results.violations.map(violation=>({id:violation.id,impact:violation.impact??null,nodes:violation.nodes.length})),
    passes:results.passes.length};
  const blocking=results.violations.filter(violation=>violation.impact==='critical'||violation.impact==='serious');
  expect(blocking.map(violation=>violation.id+': '+violation.help+' at '+violation.nodes.map(node=>node.target.join(' ')).join(', ')),
    screen+' / '+state).toEqual([]);
  expect(results.passes.length,screen+' / '+state).toBeGreaterThan(10);
  return results;
}

/** Structure every screen shares: a first-focus skip link to a focusable main
 * landmark, one h1, no positive tabindex, a name for every focusable element, and
 * a tab order that runs from the top to off the page without a trap. */
async function structure(screen:string){
  const order=tabOrder(document);
  expect(order.length,screen).toBeGreaterThan(3);
  expect(order.filter(element=>Number(element.getAttribute('tabindex')??0)>0),screen).toEqual([]);
  for(const element of order)expect(accessibleName(element),screen+': '+described(element)+' '+element.outerHTML.slice(0,120)).not.toBe('');
  expect(document.querySelectorAll('main').length).toBe(1);
  expect(document.querySelectorAll('h1').length).toBe(1);
  const user=new KeyboardUser(document);
  const first=user.tab();
  expect(first?.textContent).toBe('Skip to content');
  await act(async()=>user.press('Enter'));
  expect(document.activeElement?.tagName,screen+': the skip link moves focus to the main landmark').toBe('MAIN');
  // From the top, Tab visits every focusable element once and then leaves the page.
  const visited:HTMLElement[]=[];
  const walker=new KeyboardUser(document);
  for(let element=walker.tab();element;element=walker.tab())visited.push(element);
  expect(visited,screen+': no keyboard trap').toEqual(order);
  expect(new Set(visited).size).toBe(visited.length);
  // And Shift+Tab walks back the same way.
  const back:HTMLElement[]=[];
  for(let element=walker.shiftTab();element;element=walker.shiftTab())back.push(element);
  expect(back.reverse()).toEqual(order);
}

async function task(screen:string,name:string,run:(user:KeyboardUser)=>Promise<void>){
  const user=new KeyboardUser(document);
  const record={task:name,completed:false,steps:user.steps,navigations:user.navigations};
  entry(screen).tasks.push(record);
  await run(user);
  record.completed=true;
}
const named=(pattern:RegExp)=>(element:HTMLElement)=>pattern.test(accessibleName(element));
async function press(user:KeyboardUser,key:'Enter'|' '){await act(async()=>{user.press(key);await new Promise(done=>setTimeout(done,0));});}

