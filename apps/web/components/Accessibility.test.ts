it('Memory Inbox: automated checks pass and every core task completes from the keyboard alone',async()=>{
  const requests:Array<{url:string;init:RequestInit}>=[];
  globalThis.fetch=(async(url:string,init:RequestInit)=>{requests.push({url,init});
    return new Response(JSON.stringify(inboxDecision),{status:200,headers:{'content-type':'application/json'}});}) as typeof fetch;
  await mount(createElement(MemoryInbox,memoryInboxProps));
  await audit('Memory Inbox','card within budget');
  await structure('Memory Inbox');
  await task('Memory Inbox','Read why a question is asked and what each choice changes',async user=>{
    const why=user.tabTo(named(/^Why you are seeing this/))!;
    expect(why).not.toBeNull();
    await press(user,'Enter');
    expect((why.parentElement as HTMLDetailsElement).open).toBe(true);
    expect(why.parentElement!.textContent).toContain('Asked within today’s attention budget.');
    // Back to the choices: each announces what it will change.
    let choice:HTMLElement|null=null;
    for(let element=user.shiftTab();element;element=user.shiftTab())if(/^Confirm repayment/.test(accessibleName(element))){choice=element;break;}
    expect(choice).not.toBeNull();
    expect(document.getElementById(choice!.getAttribute('aria-describedby')!)?.textContent)
      .toBe('What will change: Records that the ₪60 transfer repaid this obligation.');
  });
  await task('Memory Inbox','Answer a card',async user=>{
    expect(user.tabTo(named(/^Confirm repayment for Possible Daniel repayment$/))).not.toBeNull();
    await press(user,'Enter');
    expect(requests).toHaveLength(1);
    expect(requests[0]!.url).toBe('/api/platform/memory/inbox/cards/'+id(1)+'/decide');
    expect(requests[0]!.init.method).toBe('POST');
    expect(JSON.parse(String(requests[0]!.init.body))).toEqual({choiceId:'confirm_repayment'});
    const headers=requests[0]!.init.headers as Record<string,string>;
    expect(headers['x-purpose']).toBe('memory.inbox');
    expect(headers['idempotency-key']).toMatch(/^[0-9a-f]{32}$/);
    // The result is announced, and the answered card has left the list.
    const recorded=document.querySelector('section[aria-labelledby=decided]');
    expect(recorded?.getAttribute('role')).toBe('status');
    expect(recorded?.textContent).toContain('Possible Daniel repayment: Confirm repayment.');
    expect(document.body.textContent).not.toContain('Why it matters');
  });
  await audit('Memory Inbox','answer recorded');
  await mount(createElement(MemoryInbox,{view:{...memoryInboxProps.view,cards:[],deferredCount:0}}));
  await audit('Memory Inbox','empty');
},CORE_VIEW_TIMEOUT_MS);

